def main():
    print('=' * 78)
    print('1군 조문 이미지 OCR 반영' + ('  [미리보기 — DB 무변경]' if DRY else ''))
    print('=' * 78)
    done = 0
    for cid, imgs in TABLES.items():
        r = sb.table('document_chunks').select('id, doc_name, article_no, content') \
            .eq('id', cid).limit(1).execute()
        if not r.data:
            print(f'{cid}: 청크 없음 — 건너뜀')
            continue
        row = r.data[0]
        new = row['content']
        for fid, md in imgs.items():
            tag = f'<img id="{fid}"></img>'
            if tag not in new:
                print(f'  ! {cid}: {tag} 없음 — 건너뜀(원본이 바뀌었을 수 있다)')
                continue
            # 원본 태그는 주석으로 보존 — 되돌릴 수 있게
            new = new.replace(tag, md + f'\n<!-- 원본 이미지: <img id="{fid}"></img> (법제처 flDownload.do?flSeq={fid}) -->\n')
        if new == row['content']:
            print(f'{cid}: 변경 없음')
            continue
        print(f"\n■ {cid} {row['doc_name'].split('(')[0][:22]} {row['article_no'][:34]}")
        print(f"   {len(row['content'])}자 → {len(new)}자  (+{len(new) - len(row['content'])})")
        if DRY:
            print('   ' + new[:200].replace('\n', ' ')[:200] + ' …')
            done += 1
            continue
        # 본문 교체 + 임베딩 NULL (backfill_embeddings.py가 NULL만 채우므로 반드시 함께)
        sb.table('document_chunks').update({'content': new, 'embedding': None}).eq('id', cid).execute()
        done += 1
        print('   ✓ 반영 + embedding NULL')

    print(f'\n{"미리보기" if DRY else "반영"} {done}건')
    if not DRY and done:
        print('→ 다음: python backfill_embeddings.py 로 임베딩 재생성')


if __name__ == '__main__':
    main()
